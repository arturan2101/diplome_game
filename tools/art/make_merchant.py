def rgb(k):
    h = P[k]
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def draw(rows, w, h):
    img = Image.new("RGBA", (w, h))
    for y, line in enumerate(rows.strip("\n").splitlines()[:h]):
        for x, key in enumerate(line[:w]):
            if key not in ". ":
                img.putpixel((x, y), rgb(key))
    return img


