def merchant_frames(hood, hood_light, pack=False):
    base = draw(MERCHANT, 24, 24)
    frames = []
    for i in range(4):
        img = base.copy()
        px = img.load()
        for y in range(24):
            for x in range(24):
                c = px[x, y]
                if c[3] and c[:3] == rgb("h")[:3]:
                    px[x, y] = rgb(hood)
                elif c[3] and c[:3] == rgb("H")[:3]:
                    px[x, y] = rgb(hood_light)
        # the lantern flickers between two glows
        if i % 2:
            for x, y in ((4, 14), (5, 15)):
                px[x, y] = rgb("Y")
        if pack:
            for y in range(11, 17):
                for x in range(19, 22):
                    px[x, y] = rgb("B") if x < 21 else rgb("b")
            px[19, 10], px[20, 10], px[21, 10] = rgb("o"), rgb("o"), rgb("o")
        # breathing: the body sinks a pixel on frames 1-2
        if i in (1, 2):
            body = img.crop((0, 0, 24, 21))
            img.paste(Image.new("RGBA", (24, 21)), (0, 0))
            img.alpha_composite(body, (0, 1))
        frames.append(img)
    return frames


def strip(frames, path):
    w, h = frames[0].size
    img = Image.new("RGBA", (w * len(frames), h))
    for i, f in enumerate(frames):
        img.paste(f, (i * w, 0))
    img.save(path)


def frames_tres(png_res, count, path, name="idle_down", speed=4.0):
    lines = [f'[gd_resource type="SpriteFrames" load_steps={2 + count} format=3]', "",
             f'[ext_resource type="Texture2D" path="{png_res}" id="strip"]', ""]
    for i in range(count):
        lines += [f'[sub_resource type="AtlasTexture" id="f{i}"]', 'atlas = ExtResource("strip")',
                  f"region = Rect2({i * 24}, 0, 24, 24)", ""]
    fr = ", ".join('{\n"duration": 1.0,\n"texture": SubResource("f%d")\n}' % i for i in range(count))
    lines += ["[resource]", 'animations = [{\n"frames": [%s],\n"loop": true,\n"name": &"%s",\n"speed": %s\n}]' % (fr, name, speed), ""]
    with open(path, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(lines))


