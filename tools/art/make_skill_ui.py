MINUS = {"cooldown"}
BADGELESS = {"magnet", "armour", "chest_luck"}


def perk(name):
    g = Grid(16, 16)
    for y, row in enumerate(PERKS[name].strip("\n").splitlines()):
        for x, key in enumerate(row):
            if key != ".":
                g.set(x, y, key)
    if name not in BADGELESS:
        if name in MINUS:
            g.rect(10, 12, 14, 12, "L")
        else:
            g.rect(10, 12, 14, 12, "V")
            g.rect(12, 10, 12, 14, "V")
    g.outline()
    return g.image()


