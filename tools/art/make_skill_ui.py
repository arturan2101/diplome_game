def strip(frames, w, h):
    img = Image.new("RGBA", (w * len(frames), h))
    for i, f in enumerate(frames):
        img.paste(f, (w * i, 0))
    return img


def node(state):
    g = Grid(20, 20)
    outer, inner, light = {"locked": ("e", "s", "S"), "available": ("y", "Y", "Z"), "bought": ("Y", "Z", "U")}[state]
    g.rect(0, 0, 19, 19, "o")
    g.rect(1, 1, 18, 18, outer)
    g.rect(1, 1, 18, 1, light)
    g.rect(1, 1, 1, 18, light)
    g.rect(2, 2, 17, 17, inner if state != "locked" else "s")
    g.rect(2, 2, 17, 17, ".")
    if state == "locked":
        g.rect(1, 1, 18, 1, "S")
        g.rect(1, 1, 1, 18, "S")
    if state == "bought":
        for x, y in ((0, 0), (19, 0), (0, 19), (19, 19)):
            g.set(x, y, "Z")
    return g.image()


def line():
    frames = []
    for fill, dark in (("e", "s"), ("Z", "Y")):
        g = Grid(8, 6)
        g.rect(0, 1, 7, 1, "o")
        g.rect(0, 2, 7, 2, fill)
        g.rect(0, 3, 7, 3, dark)
        g.rect(0, 4, 7, 4, "o")
        frames.append(g.image())
    return strip(frames, 8, 6)


def panel():
    g = Grid(24, 24)
    g.rect(0, 0, 23, 23, "o")
    g.rect(1, 1, 22, 22, "S")
    g.rect(1, 1, 22, 1, "T")
    g.rect(1, 1, 1, 22, "T")
    g.rect(2, 22, 22, 22, "e")
    g.rect(22, 2, 22, 22, "e")
    g.rect(3, 3, 20, 20, "o")
    g.rect(4, 4, 19, 19, "k")
    for x0, y0, sx, sy in ((1, 1, 1, 1), (22, 1, -1, 1), (1, 22, 1, -1), (22, 22, -1, -1)):
        for k in range(3):
            g.set(x0 + sx * k, y0, "Y")
            g.set(x0, y0 + sy * k, "Y")
        g.set(x0, y0, "Z")
    return g.image()


